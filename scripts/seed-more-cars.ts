async function main() {
  console.log("Adding realistic vehicles...");
  for (const car of NEW_CARS) {
    const existing = await db.vehicle.findUnique({ where: { id: car.id } });
    if (existing) {
      console.log(`Car ${car.id} already exists, skipping.`);
      continue;
    }
    const { images, ...data } = car;
    await db.vehicle.create({
      data: {
        ...data,
        images: {
          create: images.map((url, i) => ({
            url,
            alt: `${car.year} ${car.make} ${car.model} photo ${i + 1}`,
            sortOrder: i,
          })),
        },
      },
    });
    console.log(`Added: ${car.year} ${car.make} ${car.model}`);
  }
  const count = await db.vehicle.count({ where: { status: "PUBLISHED" } });
  console.log(`Total published vehicles now: ${count}`);
}

main().catch(console.error);
